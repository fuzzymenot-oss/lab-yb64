# Вариант 2: Оценка заполненности хранилища.
fill_level = int(input("Заполненность (% от 0 до 100): "))

# Проверка выхода за границы
if fill_level < 0 or fill_level > 100:
    print("Ошибка диапазона")
# Проверка категорий (порядок важен!)
elif fill_level >= 90:
    print("Почти заполнено")
elif fill_level >= 50:
    print("Мало места")
else:
    # Сюда попадаем только если значение >= 0 и < 50
    print("Свободно")